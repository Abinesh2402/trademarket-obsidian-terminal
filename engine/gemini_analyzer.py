"""
Gemini AI Contextual Threat Analyzer
Uses Google Gemini API to perform deep linguistic reasoning, psychological manipulation
breakdown, and victim protection guidance on suspicious communications.
"""

import os
import json
import urllib.request
import urllib.error
from typing import Dict, Any, Optional

DEFAULT_MODEL = "gemini-2.5-flash"
API_BASE_URL = "https://generativelanguage.googleapis.com/v1beta/models"


class GeminiAnalyzer:
    """Interacts with Google Gemini API for deep cyber threat analysis."""

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY", "").strip()

    def is_configured(self) -> bool:
        return bool(self.api_key)

    def analyze(self, text: str, context_type: str = "general") -> Dict[str, Any]:
        """Performs deep contextual threat analysis using Gemini.
        Returns structured analysis dict.
        """
        if not self.is_configured():
            return {
                "available": False,
                "error": "Gemini API key is not configured. Provide an API key to enable AI deep reasoning."
            }

        if not text or not text.strip():
            return {
                "available": False,
                "error": "Input text is empty."
            }

        prompt = f"""You are an elite Cyber Threat Intelligence and Fraud Prevention Analyst.
Analyze the following communication (Type: {context_type}) to determine if it is a SCAM, SPAM, PHISHING, FRAUD, or LEGITIMATE message.

Input Text:
\"\"\"
{text}
\"\"\"

Perform a deep forensic analysis and return ONLY a valid JSON object matching this exact schema:
{{
  "verdict": "CRITICAL_SCAM" | "HIGH_RISK_SPAM" | "SUSPICIOUS" | "LIKELY_LEGITIMATE",
  "ai_risk_score": <number between 0 and 100>,
  "confidence": <number between 0.0 and 1.0>,
  "scam_category": "<concise category, e.g. Courier Smishing, Bank OTP Theft, Crypto Doubler, Advance-Fee, Job Offer Scam, etc.>",
  "executive_summary": "<1-2 concise sentences summarizing the nature of the communication>",
  "psychological_triggers": [
    "<e.g. Artificial Urgency, Authority Impersonation, Fear of Loss, Greed/FOMO, Deceptive Gatekeeping>"
  ],
  "deception_mechanisms": [
    "<bullet point explaining how the attacker tries to manipulate the victim>"
  ],
  "indicators_of_compromise": [
    "<exact quote or element from text that constitutes a red flag>"
  ],
  "victim_action_plan": [
    "<specific step the recipient should take, e.g. Do not click link, Block sender, Report SMS to 7726>"
  ]
}}
"""

        url = f"{API_BASE_URL}/{DEFAULT_MODEL}:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {
                    "parts": [{"text": prompt}]
                }
            ],
            "generationConfig": {
                "temperature": 0.1,
                "responseMimeType": "application/json"
            }
        }

        try:
            req_data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(
                url,
                data=req_data,
                headers={"Content-Type": "application/json"},
                method="POST"
            )

            with urllib.request.urlopen(req, timeout=15) as resp:
                resp_body = resp.read().decode("utf-8")
                resp_json = json.loads(resp_body)

                # Extract generated text from candidates
                candidates = resp_json.get("candidates", [])
                if not candidates:
                    return {
                        "available": False,
                        "error": "No response generated by Gemini model."
                    }

                part_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                parsed_analysis = json.loads(part_text)
                parsed_analysis["available"] = True
                parsed_analysis["model"] = DEFAULT_MODEL
                return parsed_analysis

        except urllib.error.HTTPError as he:
            err_msg = f"Gemini API HTTP Error {he.code}: {he.reason}"
            try:
                err_detail = json.loads(he.read().decode("utf-8"))
                if "error" in err_detail and "message" in err_detail["error"]:
                    err_msg = f"Gemini API Error: {err_detail['error']['message']}"
            except Exception:
                pass
            return {"available": False, "error": err_msg}

        except Exception as e:
            return {"available": False, "error": f"Failed to contact Gemini API: {str(e)}"}
